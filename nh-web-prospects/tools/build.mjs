// Regenerates the client list, outreach emails and dashboard data from data/*.json.
// Usage: node tools/build.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const data = read('data/prospects.json');
const outreach = read('data/outreach.json');

const DAYS = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
const hoursText = (h) => (h ? DAYS.map((d) => `${d} ${h[d]}`).join('; ') : '');

const prospects = data.prospects.map((p) => {
  const msg = outreach.messages[p.slug];
  if (!msg) throw new Error(`No outreach message for ${p.slug}`);
  return {
    ...p,
    site: `sites/${p.slug}/index.html`,
    hasPreview: existsSync(join(root, 'sites', p.slug, 'thumb.png')),
    outreach: { ...msg, body: `${msg.body}\n\n${outreach.signature}` },
  };
});

// ---- client-list.csv ----
const csvCell = (v) => {
  const s = v == null ? '' : Array.isArray(v) ? v.join(' | ') : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const cols = [
  ['Priority', (p) => p.priority],
  ['Business', (p) => p.name],
  ['Category', (p) => p.category],
  ['Town', (p) => p.town],
  ['Address', (p) => p.address],
  ['Phone', (p) => p.phone],
  ['Email', (p) => p.email || ''],
  ['Facebook', (p) => p.facebook || ''],
  ['Instagram', (p) => p.instagram || ''],
  ['Current web presence', (p) => p.webStatus],
  ['Why they need a site', (p) => p.webEvidence],
  ['Still open? (evidence)', (p) => p.openEvidence],
  ['Hours', (p) => hoursText(p.hours)],
  ['Pitch angle', (p) => p.pitchAngle],
  ['Best way to reach', (p) => p.outreach?.channel || ''],
  ['Email subject', (p) => p.outreach?.subject || ''],
  ['Concept site', (p) => (p.site ? `nh-web-prospects/${p.site}` : '')],
  ['Status', () => 'Not contacted'],
  ['Notes', (p) => p.notes || [p.hoursNote, p.addressNote].filter(Boolean).join(' ')],
];
const rows = [
  ...prospects,
  ...data.backupLeads.map((b) => ({ ...b, priority: 'Backup', webEvidence: '', hours: null })),
];
const csv = [cols.map(([h]) => h), ...rows.map((p) => cols.map(([, f]) => f(p)))]
  .map((r) => r.map(csvCell).join(','))
  .join('\n');
writeFileSync(join(root, 'client-list.csv'), `${csv}\n`);

// ---- outreach/emails.md ----
mkdirSync(join(root, 'outreach'), { recursive: true });
const md = [
  '# Outreach drafts',
  '',
  `Generated from \`data/outreach.json\` — edit that file and re-run \`node tools/build.mjs\`.`,
  '',
  'Before sending: replace `[Your Name]`, `YOUR STUDIO`, and the contact/address placeholders; attach the',
  "site's `preview-desktop.png` (or `preview-mobile.png`); and confirm the business is still open.",
  'Only one prospect (Bigfoot Sourdough) publicly lists an email. For the rest, use the channel listed',
  '(Facebook message, phone, or stopping in) — the same text works as a Facebook message.',
  '',
  '## Phone / walk-in script',
  '',
  `> ${outreach.phoneScript}`,
  '',
  ...prospects.flatMap((p) => [
    `## ${p.id}. ${p.name} — ${p.town}`,
    '',
    `- **Reach via:** ${p.outreach.channel}`,
    `- **Phone:** ${p.phone}${p.email ? ` · **Email:** ${p.email}` : ''}`,
    `- **Attach:** \`sites/${p.slug}/preview-desktop.png\``,
    '',
    `**Subject:** ${p.outreach.subject}`,
    '',
    ...p.outreach.body.split('\n').map((l) => (l ? `> ${l}` : '>')),
    '',
  ]),
].join('\n');
writeFileSync(join(root, 'outreach', 'emails.md'), md);

// ---- data/prospects.js (dashboard data; works from file://) ----
writeFileSync(
  join(root, 'data', 'prospects.js'),
  `// Generated by tools/build.mjs — do not edit by hand.\nwindow.PROSPECTS = ${JSON.stringify(
    { researched: data.researched, method: data.method, prospects, backupLeads: data.backupLeads },
    null,
    2,
  )};\n`,
);

console.log(`Wrote client-list.csv (${rows.length} rows), outreach/emails.md, data/prospects.js`);
